// Generates out/sw.js after `next build`: precaches every file of the static
// export so the whole app (pages, content, art) works offline after first load.
// The service worker never touches IndexedDB, so updates cannot erase progress.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const OUT = "out";
const base = process.env.BASE_PATH ?? "";

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = walk(OUT)
  .map((p) => relative(OUT, p).split(sep).join("/"))
  .filter((p) => p !== "sw.js" && p !== "_headers" && !p.endsWith(".txt") && !p.endsWith(".map") && !p.startsWith("_next/static/development") && p !== "404.html" && !p.startsWith("admin/"));

const hash = createHash("sha256");
for (const f of files.sort()) hash.update(f).update(readFileSync(join(OUT, f)));
const version = hash.digest("hex").slice(0, 12);

// Clean URLs: "home/index.html" is requested as "home/".
const urls = files.map((f) => (f === "index.html" ? `${base}/` : f.endsWith("/index.html") ? `${base}/${f.slice(0, -"index.html".length)}` : `${base}/${f}`));
urls.push(`${base}/404.html`);

const sw = `/* Little Ramadan service worker — generated by scripts/generate-sw.mjs. Do not edit. */
const VERSION = ${JSON.stringify(version)};
const CACHE = "little-ramadan-" + VERSION;
const BASE = ${JSON.stringify(base)};
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then(async (cache) => {
      // Add in small batches so slow connections don't time out.
      for (let i = 0; i < PRECACHE.length; i += 20) await cache.addAll(PRECACHE.slice(i, i + 20));
    }).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("little-ramadan-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // never touch other origins
  if (url.pathname.startsWith(BASE + "/admin/") || url.pathname === BASE + "/admin") return; // the content admin is always loaded fresh
  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      let path = url.pathname;
      // Static export uses trailing slashes; map "/home" to "/home/".
      if (!path.endsWith("/") && !path.split("/").pop().includes(".")) path += "/";
      const hit = (await cache.match(path)) || (await cache.match(req, { ignoreSearch: true }));
      if (hit) return hit;
      try {
        const res = await fetch(req);
        if (res.ok && res.type === "basic") cache.put(req, res.clone());
        return res;
      } catch (err) {
        if (req.mode === "navigate") return (await cache.match(BASE + "/home/")) || (await cache.match(BASE + "/")) || Response.error();
        return Response.error();
      }
    })()
  );
});
`;

writeFileSync(join(OUT, "sw.js"), sw);
console.log(`sw.js: ${urls.length} files precached, version ${version}`);
